export const getRuleTodaySuggestion = (rule: SettingsRuleRow): string => {
  if (!isSettingsEmpty(rule.nextAction)) return rule.nextAction;
  if (!isSettingsEmpty(rule.todaySuggestion)) return rule.todaySuggestion;
  return rule.judgment.nextStep;
};

