export const filterSettingsRules = (
  rules: SettingsRuleRow[],
  segment: SettingsWorkbenchSegment,
  filters: SettingsListFilters,
): SettingsRuleRow[] => {
  const q = filters.query.trim().toLowerCase();
  return rules.filter(r => {
    if (r.segment !== segment) return false;
    if (filters.status !== '全部' && r.status !== filters.status) return false;
    if (filters.sensitivity !== '全部' && r.sensitivity !== filters.sensitivity) return false;
    if (filters.port !== '全部' && !r.affectedPorts.includes(filters.port)) return false;
    if (filters.conflictOnly && r.status !== '存在冲突' && r.conflictReason === '—') return false;
    if (filters.pendingOnly && !/待审核|待发布|草稿/.test(r.status)) return false;
    if (!q) return true;
    const hay = `${r.ruleName} ${r.ruleId} ${r.applicableProducts} ${r.applicableStores} ${r.affectedPorts.join(' ')} ${r.editableRoles}`.toLowerCase();
    return hay.includes(q);
  });
};

export const computeSettingsSegmentMiniSummary = (
  snapshot: SettingsOperationSnapshot,
  segment: SettingsWorkbenchSegment,
): { label: string; value: string }[] => {
  const rows = snapshot.rules.filter(r => r.segment === segment);
  const published = rows.filter(r => r.status === '已发布').length;
  const pending = rows.filter(r => /待审核|待发布|草稿/.test(r.status)).length;
  const risk = rows.filter(r => r.displayRisk !== '—').length;
  const sensitive = rows.filter(r => r.sensitivity === '敏感' || r.sensitivity === '高敏感').length;
  return [
    { label: '本段规则', value: `${rows.length} 条` },
    { label: '已发布', value: `${published} 条` },
    { label: '待处理', value: `${pending} 条` },
    { label: '风险项', value: `${risk} 项` },
    { label: '敏感', value: `${sensitive} 条` },
  ].slice(0, 4);
};

