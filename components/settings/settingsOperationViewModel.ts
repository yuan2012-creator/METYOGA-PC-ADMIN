const buildKeyImpacts = (r: RuleBase): SettingsKeyImpacts => ({
  booking: r.linkedModules.includes('预约'),
  asset: !/无/.test(r.assetImpact) && r.assetImpact !== '—',
  finance: !/无/.test(r.financeImpact) && r.financeImpact !== '—',
  contract: !/无/.test(r.contractImpact) && r.contractImpact !== '—',
  auditRequired: !/—/.test(r.sync.audit) && r.sync.audit !== '不影响',
});

const buildRiskDetails = (r: RuleBase): SettingsRiskDetailItem[] => {
  const level =
    r.sensitivity === '高敏感' ? '高' : r.sensitivity === '敏感' ? '中' : r.displayRisk !== '—' ? '中' : '低';
  const items: SettingsRiskDetailItem[] = r.riskChecks.map(check => ({
    item: check,
    module: r.linkedModules.join(' / ') || r.ruleType,
    level,
    suggestion: r.judgment.nextStep,
  }));
  if (r.conflictReason !== '—') {
    items.unshift({
      item: '规则冲突',
      module: '三端口径',
      level: '高',
      suggestion: '对齐会员端、PC 后台与老师端后提交审核预览',
    });
  }
  if (r.missingConfigReason !== '—') {
    items.push({
      item: r.missingConfigReason,
      module: '配置完整性',
      level: '中',
      suggestion: '补全配置项后再申请发布预览',
    });
  }
  if (items.length === 0) {
    items.push({
      item: '常规巡检',
      module: r.ruleType,
      level: '低',
      suggestion: r.judgment.nextStep,
    });
  }
  return items.slice(0, 6);
};

